  ITextContent,
  Model<ITextContent>
>({
  singleton: {
    type: String,
    required: true,
    immutable: true,
    unique: true,
    trim: true,
    enum: ["SINGLETON"],
    default: "SINGLETON",
  },
  ...contentKeys.reduce(
    (acc, key) => ({ ...acc, [key]: { type: String, default: key } }),
    {},
  ),
});


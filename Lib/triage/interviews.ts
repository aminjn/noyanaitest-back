// The health chat's interviews, one per body area (2026-10, owner request:
// the small model on the site's own server asked pointless questions -
// «where is the pain?» right after «my buttock hurts», offering head / neck).
//
// Benchmark: Ada and K Health do not let a language model improvise the
// questions; each complaint has a curated interview (where exactly, since
// when, what makes it worse, what comes with it, the red flags) and the
// model only writes up the result. NoyanAI does the same: the site asks
// these questions itself (no model call, no wait), an answer marked as an
// emergency stops the interview with the 115 advice at once, and the
// model then writes the assessment from the answers, choosing among the
// conditions listed here.
//
// Each interview is matched on the patient's own Persian words (first match
// wins, so the most specific come first). The questions adapt to the
// answers: one is skipped when the patient's words already answer it
// (`skipIf`), and a follow-up is asked only after a given answer (`when`).
// An answer's `flag` sets the least urgency of the result («emergency» ends
// the interview at once), and an interview's `rules` raise it for a
// combination of answers (a fever in a baby under three months). A question
// with an emergency answer is a warning-sign question: left unclear, the
// result is not «no hurry» (missing is not the same as absent).

export type Flag = "emergency" | "soon";
export type Answer = { label: string; flag?: Flag };
export type Question = {
  id: string;
  q: string;
  answers: Answer[];
  skipIf?: RegExp;
  // asked only when every listed earlier answer is one of these
  when?: { q: string; any: string[] }[];
};
export type Interview = {
  id: string;
  words: RegExp;
  questions: Question[];
  // conditions the assessment chooses among (names the site's pages use)
  conditions: string[];
  rules?: { when: { q: string; any: string[] }[]; flag: Flag }[];
  // said with an emergency instead of the general 115 line
  emergencyNote?: string;
};

const a = (label: string, flag?: Flag): Answer => ({ label, ...(flag ? { flag } : {}) });
const none = a("هیچ‌کدام");


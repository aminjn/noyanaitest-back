export type ContentNamespace = keyof typeof contentNamespaces;

export const isContentNamespace = (ns: string): ns is ContentNamespace =>
  Object.prototype.hasOwnProperty.call(contentNamespaces, ns);

// Flattens one or more namespace names into a deduped list of ContentKeys.
// Unknown namespace names are silently ignored.
export const getNamespaceKeys = (namespaces: string[]): ContentKey[] => {
  const set = new Set<ContentKey>();
  for (const ns of namespaces) {
    if (!isContentNamespace(ns)) continue;
    for (const key of contentNamespaces[ns]) set.add(key);
  }
  return Array.from(set);
};

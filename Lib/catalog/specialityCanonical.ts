// Built from the Medical Council of Iran (سازمان نظام پزشکی) and the
// Ministry of Health's residency / subspecialty / fellowship programmes
// (دبیرخانه شورای آموزش پزشکی و تخصصی): the clinical specialities
// (تخصص), their subspecialities (فوق تخصص) and the common fellowships
// (فلوشیپ), with the parent each one grows out of, plus the general
// practitioner, dentistry and the allied professions a directory lists.
//
// `syn` are the other names people and partner directories write the same
// field as («زنان» / «زنان، زایمان و نازایی» for «زنان و زایمان», «ENT» for
// «گوش و حلق و بینی»). They are compared through Lib/catalog/catalogMatch.ts
// (no level words, letters unified, no spaces / punctuation), so a synonym
// only needs to be listed once in one spelling.
//
// Seeded by Lib/catalog/seedSpecialities.ts: an existing speciality with the
// same normalised name (or a synonym) becomes the canonical one (its slug,
// doctors and page stay); the rest are created. Nothing is deleted.

export type SpecialityTier = "general" | "specialty" | "subspecialty" | "fellowship" | "allied";

export type CanonicalSpeciality = {
  fa: string;
  en: string;
  tier: SpecialityTier;
  // the Persian name of the speciality it grows out of
  parent?: string;
  syn?: string[];
};

